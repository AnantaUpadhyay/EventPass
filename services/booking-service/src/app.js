const { createApp, errors, internal, asyncRoute } = require('../../../shared/http');
const db = require('./config/db');
const redis = require('./config/redis');
const c = require('./controllers/booking.controller');
const app = createApp('booking-service', () => ({ mongo: db.ready(), redis: redis.ready() }));
app.get('/internal/counts', internal, asyncRoute(c.counts));
app.get('/internal/outbox', internal, asyncRoute(c.pending));
app.post('/internal/outbox/:bookingId/ack', internal, asyncRoute(c.ack));
app.use('/api/booking', require('./routes/booking.routes'));
module.exports = { app: errors(app), db, redis };
